    def _generate_metric_cards(self, metrics: Dict[str, Any]) -> str:
        """Generate HTML for metric cards."""
        cards = []
        
        metric_display = {
            "total_trades": ("Total Trades", "", "number"),
            "win_rate": ("Win Rate", "%", "percentage"),
            "total_pnl": ("Total P&L", " EUR", "currency"),
            "avg_pnl_per_trade": ("Avg P&L/Trade", " EUR", "currency"),
            "sharpe_ratio": ("Sharpe Ratio", "", "number"),
            "max_drawdown": ("Max Drawdown", "%", "percentage"),
            "profit_factor": ("Profit Factor", "", "number"),
            "best_trade": ("Best Trade", " EUR", "currency"),
            "worst_trade": ("Worst Trade", " EUR", "currency"),
        }
        
        for key, (label, suffix, format_type) in metric_display.items():
            if key in metrics:
                value = metrics[key]
                
                if format_type == "percentage":
                    formatted = f"{value:.2f}"
                    css_class = "positive" if value > 50 else "negative"
                elif format_type == "currency":
                    formatted = f"{value:,.2f}"
                    css_class = "positive" if value > 0 else "negative" if value < 0 else ""
                else:
                    formatted = f"{value:.2f}" if isinstance(value, float) else str(value)
                    css_class = ""
                
                cards.append(f"""
                <div class="metric-card">
                    <div class="metric-label">{label}</div>
                    <div class="metric-value {css_class}">{formatted}{suffix}</div>
                </div>
                """)
        
        return "\n".join(cards)
    
    def _export_pdf(self, metrics: Dict[str, Any], user_name: str) -> bytes:
        """
        Export analytics to PDF.
        
        Note: This is a placeholder. In production, use reportlab or weasyprint.
        """
        # For now, return HTML with PDF content-type note
        html = self._export_html(metrics, user_name)
        return html
    
    def generate_leaderboard_export(
        self,
        leaderboard: List[Dict[str, Any]],
        format: str = "json",
    ) -> bytes:
        """Export leaderboard data."""
        data = {
            "exported_at": datetime.utcnow().isoformat(),
            "leaderboard_size": len(leaderboard),
            "rankings": leaderboard,
        }
        
        if format == "json":
            return json.dumps(data, indent=2).encode("utf-8")
        elif format == "csv":
            import csv
            from io import StringIO
            
            output = StringIO()
            if leaderboard:
                writer = csv.DictWriter(output, fieldnames=leaderboard[0].keys())
                writer.writeheader()
                writer.writerows(leaderboard)
            
            return output.getvalue().encode("utf-8")
        else:
            raise ValueError(f"Unsupported format: {format}")


